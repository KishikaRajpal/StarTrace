"""
api/report.py - Report generation endpoints for PDF and CSV export.
"""

import io
import csv
import json
import logging
from datetime import datetime

from fastapi import APIRouter, Depends, HTTPException
from fastapi.responses import StreamingResponse
from sqlalchemy.orm import Session

from ..database.session import get_db
from ..services.analysis_service import get_analysis_by_id

logger = logging.getLogger("startrace.report")
router = APIRouter(prefix="/api/report", tags=["Reports"])


@router.get("/{analysis_id}/csv")
def download_csv_report(analysis_id: str, db: Session = Depends(get_db)):
    """Generates and downloads a CSV summary report for the given analysis."""
    result = get_analysis_by_id(analysis_id, db)
    if not result:
        raise HTTPException(status_code=404, detail="Analysis not found.")

    output = io.StringIO()
    writer = csv.writer(output)

    clf = result.get("classification") or {}
    bls = result.get("bls_stats") or {}
    tp = result.get("transit_parameters") or {}

    writer.writerow(["StarTrace Analysis Report"])
    writer.writerow(["Generated", datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC")])
    writer.writerow([])

    writer.writerow(["IDENTIFICATION"])
    writer.writerow(["Analysis ID", analysis_id])
    writer.writerow(["TIC ID", result.get("tic_id", "")])
    writer.writerow(["Data Source", result.get("data_source", "")])
    writer.writerow(["Synthetic Data", "Yes" if result.get("is_synthetic") else "No"])
    writer.writerow([])

    writer.writerow(["CLASSIFICATION RESULT"])
    writer.writerow(["Predicted Class", clf.get("predicted_class", "")])
    writer.writerow(["Confidence", f"{clf.get('confidence_pct', 0):.2f}%"])
    writer.writerow(["Status", tp.get("status_label", "")])
    writer.writerow([])

    writer.writerow(["CLASS PROBABILITIES"])
    for cls_name, prob in (clf.get("probabilities") or {}).items():
        writer.writerow([cls_name, f"{prob*100:.2f}%"])
    writer.writerow([])

    writer.writerow(["BLS DETECTION RESULTS"])
    writer.writerow(["Orbital Period (days)", bls.get("period_days", "")])
    writer.writerow(["Transit Epoch (BJD)", bls.get("transit_epoch_bjd", "")])
    writer.writerow(["Transit Duration (hours)", bls.get("duration_hours", "")])
    writer.writerow(["Transit Depth (%)", bls.get("depth_pct", "")])
    writer.writerow(["Transit Depth (ppm)", bls.get("depth_ppm", "")])
    writer.writerow(["SNR", bls.get("snr", "")])
    writer.writerow(["BLS Max Power", bls.get("max_power", "")])
    writer.writerow([])

    if tp.get("is_candidate"):
        writer.writerow(["EXOPLANET CANDIDATE ESTIMATES"])
        writer.writerow(["Note", "These are physical estimates only, not confirmed planetary measurements."])
        writer.writerow(["Planet Radius (Earth radii)", tp.get("estimated_planet_radius_earth", "")])
        writer.writerow(["Semi-Major Axis (AU)", tp.get("estimated_semi_major_axis_au", "")])
        writer.writerow(["Equilibrium Temperature (K)", tp.get("estimated_equilibrium_temp_k", "")])
        writer.writerow([])

    writer.writerow(["INTERPRETATION"])
    writer.writerow([tp.get("interpretation", "")])
    writer.writerow([])
    writer.writerow(["Generated by StarTrace – Discovering Hidden Worlds Through Stellar Light."])
    writer.writerow(["Data source: NASA TESS / MAST. This tool is for educational and research purposes only."])

    output.seek(0)
    return StreamingResponse(
        io.BytesIO(output.getvalue().encode("utf-8")),
        media_type="text/csv",
        headers={"Content-Disposition": f'attachment; filename="startrace_{analysis_id[:8]}.csv"'}
    )


@router.get("/{analysis_id}/pdf")
def download_pdf_report(analysis_id: str, db: Session = Depends(get_db)):
    """Generates and downloads a formatted PDF analysis report."""
    result = get_analysis_by_id(analysis_id, db)
    if not result:
        raise HTTPException(status_code=404, detail="Analysis not found.")

    try:
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
        from reportlab.lib.units import cm
        from reportlab.lib import colors
        from reportlab.platypus import (
            SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
        )

        buffer = io.BytesIO()
        doc = SimpleDocTemplate(buffer, pagesize=A4,
                                leftMargin=2*cm, rightMargin=2*cm,
                                topMargin=2*cm, bottomMargin=2*cm)

        styles = getSampleStyleSheet()
        title_style = ParagraphStyle("Title", parent=styles["Title"],
                                     fontSize=20, spaceAfter=6, textColor=colors.HexColor("#0a0f1e"))
        h2_style = ParagraphStyle("H2", parent=styles["Heading2"],
                                   fontSize=13, spaceBefore=12, spaceAfter=4,
                                   textColor=colors.HexColor("#0d4f8c"))
        body_style = styles["BodyText"]
        body_style.fontSize = 10

        clf = result.get("classification") or {}
        bls = result.get("bls_stats") or {}
        tp = result.get("transit_parameters") or {}

        def kv_table(data, col_widths=(7*cm, 10*cm)):
            t = Table(data, colWidths=col_widths)
            t.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#eaf4ff")),
                ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#c0d8f0")),
                ("FONTSIZE", (0, 0), (-1, -1), 9),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("RIGHTPADDING", (0, 0), (-1, -1), 8),
            ]))
            return t

        story = []
        story.append(Paragraph("⭐ StarTrace Analysis Report", title_style))
        story.append(Paragraph("Discovering Hidden Worlds Through Stellar Light", styles["Italic"]))
        story.append(Spacer(1, 0.4*cm))
        story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#0d4f8c")))
        story.append(Spacer(1, 0.3*cm))

        story.append(Paragraph("Identification", h2_style))
        story.append(kv_table([
            ["Analysis ID", analysis_id],
            ["TIC ID", result.get("tic_id", "")],
            ["Data Source", result.get("data_source", "")],
            ["Synthetic Data", "Yes" if result.get("is_synthetic") else "No"],
            ["Generated", datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC")]
        ]))

        story.append(Paragraph("Classification Result", h2_style))
        story.append(kv_table([
            ["Predicted Class", clf.get("predicted_class", "")],
            ["Confidence", f"{clf.get('confidence_pct', 0):.2f}%"],
            ["Status", tp.get("status_label", "")]
        ]))

        story.append(Paragraph("Class Probabilities", h2_style))
        prob_rows = [["Class", "Probability"]]
        for cls_name, prob in (clf.get("probabilities") or {}).items():
            prob_rows.append([cls_name, f"{prob * 100:.2f}%"])
        story.append(kv_table(prob_rows))

        story.append(Paragraph("BLS Detection Results", h2_style))
        story.append(kv_table([
            ["Orbital Period (days)", str(bls.get("period_days", "—"))],
            ["Transit Epoch (BJD)", str(bls.get("transit_epoch_bjd", "—"))],
            ["Transit Duration (hours)", str(bls.get("duration_hours", "—"))],
            ["Transit Depth (%)", str(bls.get("depth_pct", "—"))],
            ["Transit Depth (ppm)", str(bls.get("depth_ppm", "—"))],
            ["SNR", str(bls.get("snr", "—"))],
            ["BLS Max Power", str(bls.get("max_power", "—"))]
        ]))

        if tp.get("is_candidate"):
            story.append(Paragraph("Exoplanet Candidate Estimates", h2_style))
            story.append(Paragraph(
                "<i>Note: These are model-based physical estimates only, not confirmed planetary measurements.</i>",
                body_style
            ))
            story.append(kv_table([
                ["Planet Radius (Earth radii)", str(tp.get("estimated_planet_radius_earth", "—"))],
                ["Semi-Major Axis (AU)", str(tp.get("estimated_semi_major_axis_au", "—"))],
                ["Equilibrium Temperature (K)", str(tp.get("estimated_equilibrium_temp_k", "—"))]
            ]))

        story.append(Paragraph("Scientific Interpretation", h2_style))
        interp = tp.get("interpretation") or clf.get("description", "")
        story.append(Paragraph(interp, body_style))

        story.append(Spacer(1, 0.6*cm))
        story.append(HRFlowable(width="100%", thickness=0.5, color=colors.grey))
        story.append(Spacer(1, 0.2*cm))
        story.append(Paragraph(
            "Generated by StarTrace | NASA TESS Data | For educational and academic research use only.",
            ParagraphStyle("footer", parent=styles["Normal"], fontSize=7, textColor=colors.grey)
        ))

        doc.build(story)
        buffer.seek(0)

        return StreamingResponse(
            buffer,
            media_type="application/pdf",
            headers={"Content-Disposition": f'attachment; filename="startrace_{analysis_id[:8]}.pdf"'}
        )

    except ImportError:
        raise HTTPException(
            status_code=500,
            detail="PDF generation library (reportlab) not installed. Use CSV export instead."
        )
    except Exception as e:
        logger.error(f"PDF generation error: {e}", exc_info=True)
        raise HTTPException(status_code=500, detail=f"PDF generation failed: {str(e)}")
